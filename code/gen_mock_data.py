def fillers(n=60):
    """正常履约合同：票款差在 0.3% 以内、已结算不超过合同额，用于形成真实分布的背景样本"""
    out = []
    for i in range(n):
        amount = D(200000 + (i * 37193) % 7800000) // 100 * 100
        rate = D(20 + (i * 7) % 70) / 100
        settle = (amount * rate) // 100 * 100
        pay = (settle * D(90 + (i % 9)) / 100) // 100 * 100
        inv = (pay * D(1000 + ((i % 7) - 3)) / 1000) // 100 * 100
        subj = SUBJECTS[i % len(SUBJECTS)]
        out.append((f"CG-2025{i + 1:03d}", f"{subj}采购合同", subj, i % 4, i % 8,
                    "N01", "N02", "T00", "CNY", f"{amount:.2f}", f"{settle:.2f}",
                    f"{inv:.2f}", f"{pay:.2f}"))
    return out


def sign_dates(i):
    m = (i % 12) + 1
    return f"2025-{m:02d}-{(i % 27) + 1:02d}"


