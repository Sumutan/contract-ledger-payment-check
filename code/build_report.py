def main():
    payload = json.load(open(os.path.join(BASE, "out", "clues.json"), encoding="utf-8"))

    # 线索字段名映射为「输出契约」的中文列名，与 out/clue_list.csv 保持一致
    keys = [("clue_id", "线索ID"), ("rule", "规则编号"), ("rule_name", "规则名称"),
            ("candidate_id", "候选ID"), ("contract_code", "合同编号"), ("contract_name", "合同名称"),
            ("member_name", "成员单位"), ("contract_type", "合同类型"),
            ("c1", "合同金额C1"), ("e1", "已结算金额E1"),
            ("b2", "累计发票金额B2"), ("s2", "累计支付金额S2"),
            ("diff", "差异金额"), ("ratio", "差异率"), ("score", "风险评分"),
            ("level", "风险等级"), ("reason", "风险理由"), ("advice", "排查建议")]
    mapped = []
    for c in payload["clues"]:
        d = {}
        for src, dst in keys:
            v = c.get(src)
            if src == "ratio":
                v = f"{float(v) * 100:.2f}%"
            elif src == "score":
                v = f"{float(v):.1f}"
            d[dst] = v
        d["快照日"] = payload["params"]["snapshot_date"]
        mapped.append(d)
    payload["clues"] = mapped

    payload["design"] = [dict(no=a, code=b, intent=c, expect=d) for a, b, c, d in DESIGN]
    payload["dict"] = [list(x) for x in DICT]

    html = open(TPL, encoding="utf-8").read()
    js = json.dumps(payload, ensure_ascii=False).replace("</", "<\\/")
    html = html.replace("__PAYLOAD__", js)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"✓ 已生成：{OUT}")
    v = payload["v21"]
    print(f"  线索 {len(payload['clues'])} 条 ｜ 特征 {len(payload['features'])} 行 ｜ "
          f"证据集 {len(v['_set'])} 组 / 明细 {len(v['_detail'])} 行 ｜ "
          f"{os.path.getsize(OUT) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
